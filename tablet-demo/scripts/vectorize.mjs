// Turns the supplied reference drawings (src/sketches/assets/source/*.png) into
// resolution-independent SVG paths, so the app draws them inline: no image files
// to load, sharp at any zoom. Run again after replacing a source image:
//
//   node scripts/vectorize.mjs   -> src/sketches/assets/vectors.ts
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import potrace from 'potrace';
import { launch } from './browser.mjs';

const DIR = fileURLToPath(new URL('../src/sketches/assets/', import.meta.url));
const SCALE = 2; // trace at 3x for smooth curves, scaled back in the app
const BG = [237, 234, 226]; // background colour of the supplied drawings

const trace = (png, params) =>
  new Promise((resolve, reject) =>
    potrace.trace(png, params, (err, svg) => {
      if (err) return reject(err);
      const d = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(' ');
      resolve(d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(parseFloat(n) * 10) / 10)));
    }),
  );

const browser = await launch();
const page = await browser.newPage();
await page.setContent('<canvas id="c"></canvas>');

const names = readdirSync(DIR + 'source').filter((f) => f.endsWith('.png'));
const out = {};
for (const file of names) {
  const url = 'data:image/png;base64,' + readFileSync(DIR + 'source/' + file).toString('base64');
  const { ink, paper, w, h } = await page.evaluate(
    async ({ url, SCALE, BG }) => {
      const img = new Image();
      img.src = url;
      await img.decode();
      const w = img.width;
      const h = img.height;
      const c = document.getElementById('c');
      c.width = w * SCALE;
      c.height = h * SCALE;
      const g = c.getContext('2d', { willReadFrequently: true });
      g.imageSmoothingEnabled = true;
      g.imageSmoothingQuality = 'high';
      g.drawImage(img, 0, 0, c.width, c.height);
      const data = g.getImageData(0, 0, c.width, c.height);
      const mask = (test) => {
        const m = g.createImageData(c.width, c.height);
        for (let i = 0; i < data.data.length; i += 4) {
          const [r, gg, b] = [data.data[i], data.data[i + 1], data.data[i + 2]];
          const on = test(r, gg, b);
          const v = on ? 0 : 255;
          m.data[i] = m.data[i + 1] = m.data[i + 2] = v;
          m.data[i + 3] = 255;
        }
        g.putImageData(m, 0, 0);
        return c.toDataURL('image/png');
      };
      // ink: the dark line work; paper: everything that is not the beige ground (so no seams show)
      const ink = mask((r, gg, b) => (r + gg + b) / 3 < 150);
      const paper = mask((r, gg, b) => Math.abs(r - BG[0]) + Math.abs(gg - BG[1]) + Math.abs(b - BG[2]) > 14);
      return { ink, paper, w, h };
    },
    { url, SCALE, BG },
  );
  const buf = (u) => Buffer.from(u.split(',')[1], 'base64');
  const params = { turdSize: 4, alphaMax: 1, optCurve: true, optTolerance: 0.9, threshold: 128 };
  const name = file.replace('.png', '');
  out[name] = { w, h, ink: await trace(buf(ink), params), paper: await trace(buf(paper), { ...params, turdSize: 300, optTolerance: 6, alphaMax: 1.2 }) };
  console.log(name, `${(out[name].ink.length / 1024).toFixed(0)} KB ink, ${(out[name].paper.length / 1024).toFixed(0)} KB paper`);
}
await browser.close();

const lines = Object.entries(out).map(
  ([n, v]) => `  '${n}': { w: ${v.w}, h: ${v.h}, ink: '${v.ink}', paper: '${v.paper}' },`,
);
writeFileSync(
  DIR + 'vectors.ts',
  `// Generated by scripts/vectorize.mjs from assets/source/*.png — do not edit by hand.\n// Paths are traced at ${SCALE}x; draw them inside scale(1/${SCALE}).\nexport const TRACE_SCALE = ${SCALE};\n\nexport interface TracedDrawing {\n  w: number;\n  h: number;\n  ink: string;\n  paper: string;\n}\n\nexport const DRAWINGS: Record<string, TracedDrawing> = {\n${lines.join('\n')}\n};\n`,
);
